#!/usr/bin/env node
// Writes backend/src/convexModules.gen.ts: the static import map of every
// Convex function module, using Convex's own entry-point rules (files in
// convex/ whose path has no segment starting with "_" or "." and whose
// basename has exactly one dot). Generated, never committed: wrangler runs it
// before bundling (`build.command`), vitest as `globalSetup`, and
// `bun run backend:type-check` before tsc.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const backendDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const convexDir = join(backendDir, "..", "convex");
const target = join(backendDir, "src", "convexModules.gen.ts");

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith("_") || entry.name.startsWith(".")) return [];
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return walk(path);
    const isModule = /\.(ts|tsx|js|jsx)$/.test(entry.name) && entry.name.split(".").length === 2;
    return isModule ? [path] : [];
  });
}

function generate() {
  const modules = walk(convexDir)
    .map((path) => relative(convexDir, path).replace(/\\/g, "/").replace(/\.(ts|tsx|js|jsx)$/, ""))
    .sort();
  const source = [
    "// Generated by backend/scripts/generate-modules.mjs. Do not edit.",
    "// Static map of Convex function modules for the Cloudflare host.",
    ...modules.map((name, i) => `import * as m${i} from "../../convex/${name}";`),
    "",
    "export const convexModules: Record<string, Record<string, unknown>> = {",
    ...modules.map((name, i) => `  ${JSON.stringify(name)}: m${i},`),
    "};",
    "",
  ].join("\n");
  let current = null;
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // first run
  }
  if (current !== source) writeFileSync(target, source);
  return modules.length;
}

/** Vitest `globalSetup` hook. */
export function setup() {
  generate();
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  console.log(`convexModules.gen.ts: ${generate()} Convex modules`);
}
